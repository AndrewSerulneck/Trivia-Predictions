import { isMultiVenueBillingEnabled } from "@/lib/multiVenueBilling";
import { rateLimit } from "@/lib/rateLimit";
import { requireOwnerAuth } from "@/lib/requireOwnerAuth";
import { SIGNUP_MAX_BODY_BYTES } from "@/lib/selfServeSignup";
import {
  addVenueInputFromBody,
  addVenueInputIssue,
  addVenueResponse,
  isValidClientKey,
  loadAddVenueContext,
  rateLimitRefusal,
  startVenueAddition,
} from "@/lib/venueAddition";
import { settleStaleVenueChangesForBill } from "@/lib/venueRemoval";

/**
 * POST /api/owner/venues/add — a partner adds another venue to their bill, paying the prorated
 * band price on their card now (docs/multi-venue-volume-billing-plan.md §4.3, Phase 3).
 *
 * Gate order: flag (404 when off) → owner session → owner rate limit → body → input rules →
 * healthy bill → the add itself. Every decision lives in lib/venueAddition.ts; this file only
 * parses and answers.
 *
 * Body: `{ idempotencyKey, venueId?, venueName, street, city, state, zipCode, placeId, latitude,
 * longitude, radius, prorationDate?, quotedVenueCents }` — or, for an "Add back" of a venue taken off this bill
 * (Phase 5), `{ idempotencyKey, venueId?, readdVenueId, prorationDate?, quotedVenueCents }` with no address fields. `idempotencyKey` is generated by the client once per
 * "Confirm" and re-sent on every retry of that confirm: the same key always means the same add
 * (never a second charge or a second venue), so re-POSTing it is also how the client asks "how
 * did it go?" after 3-D Secure. `venueId` is the dashboard's selected venue — its bill is the one
 * added to. `prorationDate` and `quotedVenueCents` (the quote's `thisVenueCents`) come from the quote; a
 * price that no longer matches is refused `quote_changed` (409) before anything is charged.
 *
 * Answers: 200 `{ status: "paid", venueId }` (live now) · 202 `{ status: "requires_action",
 * hostedInvoiceUrl }` (3-D Secure on Stripe's page; the venue goes live when it is paid) · 202
 * `{ status: "processing" }` (ask again shortly) · or `{ ok: false, code, error }`.
 */
export async function POST(request: Request) {
  if (!isMultiVenueBillingEnabled()) {
    return new Response(JSON.stringify({ ok: false, error: "Not found." }), {
      status: 404,
      headers: { "Content-Type": "application/json" },
    });
  }

  let auth;
  try {
    auth = await requireOwnerAuth(request);
  } catch (response) {
    return response as Response;
  }

  const limit = await rateLimit(request, "venueAddOwner", { identity: auth.ownerId, ignoreIp: true });
  if (!limit.allowed) {
    return addVenueResponse(rateLimitRefusal(limit), { "Retry-After": String(Math.max(1, limit.retryAfterSeconds)) });
  }

  // Bounded like POST /api/owner/signup: refuse an oversized body on Content-Length before reading
  // it, then re-check the decoded byte length (the header is absent on a chunked request).
  const declared = Number(request.headers.get("content-length") ?? "");
  if (Number.isFinite(declared) && declared > SIGNUP_MAX_BODY_BYTES) {
    return addVenueResponse({ ok: false, httpStatus: 413, code: "invalid_request", error: "That request was too large." });
  }
  const raw = await request.text().catch(() => "");
  if (Buffer.byteLength(raw, "utf8") > SIGNUP_MAX_BODY_BYTES) {
    return addVenueResponse({ ok: false, httpStatus: 413, code: "invalid_request", error: "That request was too large." });
  }
  let body: Record<string, unknown> = {};
  try {
    const parsed: unknown = JSON.parse(raw || "{}");
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) body = parsed as Record<string, unknown>;
  } catch {
    body = {};
  }

  const clientKey = typeof body.idempotencyKey === "string" ? body.idempotencyKey.trim() : "";
  if (!isValidClientKey(clientKey)) {
    return addVenueResponse({
      ok: false,
      httpStatus: 400,
      code: "invalid_request",
      error: "Something about that request wasn't right. Please start again.",
    });
  }

  const readdVenueId = typeof body.readdVenueId === "string" ? body.readdVenueId.trim() || null : null;
  const input = addVenueInputFromBody(body);
  if (!readdVenueId) {
    const issue = addVenueInputIssue(input);
    if (issue) return addVenueResponse({ ok: false, httpStatus: 400, code: "invalid_request", error: issue });
  }

  const preferredVenueId = typeof body.venueId === "string" ? body.venueId.trim() || null : null;
  const loaded = await loadAddVenueContext(auth, preferredVenueId);
  if (!loaded.ok) return addVenueResponse(loaded);

  // A Remove / Undo that died mid-request would otherwise keep this bill "busy" until the daily cron.
  await settleStaleVenueChangesForBill(loaded.context.bill.id);

  const outcome = await startVenueAddition({
    auth,
    context: loaded.context,
    input,
    readdVenueId,
    clientKey,
    prorationDate: body.prorationDate,
    quotedVenueCents: body.quotedVenueCents,
  });
  return addVenueResponse(outcome);
}
