import { beforeAll, describe, expect, it, vi } from "vitest";

import fixtureGames from "@/tests/fixtures/mlb-completed-games-2026.json";

vi.mock("server-only", () => ({}));

/**
 * Phase 7 of docs/prop-bingo-nfl-plan.md — does an MLB board actually land at a 20-30% win rate?
 *
 * The MLB counterpart to `tests/lib.sportsBingo.win-rate-calibration.test.ts`, and deliberately a
 * **separate file** rather than an extension of it, which is a documented deviation from the plan's
 * text. The reason is mechanical: an MLB board is mostly the team-event block, which is assembled
 * asynchronously from `/mlb/v1/stats`, so this slate has to mock `@/lib/ballDontLieClient` — and
 * `vi.mock` is file-scoped, so putting it in the NFL file would drag the (currently mock-free,
 * network-free) NFL slate through the same stub.
 *
 * The slate is **frozen and real**: thirteen completed 2026 MLB games checked in at
 * `tests/fixtures/mlb-completed-games-2026.json`, spread from one-run finishes to a six-run margin,
 * carrying each game's final score and each team's real box-score totals for the six measured
 * events. Boards are generated by the shipped pipeline and settled by the shipped
 * `gradeResolversAgainstCompletedMLBGame`, so this is the real generator against real outcomes.
 *
 * What it is not: MLB player-prop squares are absent here, because this fixture's mock answers
 * `/mlb/v1/odds/player_props` with nothing and the historical-stat path needs a player pool this
 * compact fixture does not carry. That is deliberate — it isolates the team-event block Phase 7
 * re-priced, which is what these assertions are about. It is **no longer** a description of
 * production: Phase 9d repaired the prop feed (the 404 was a wrong route, not a missing feed), so a
 * real MLB board now carries book-posted player props again. Their selection is covered by
 * tests/lib.sportsBingo.mlb-star-tilt.test.ts and their pricing by
 * tests/lib.sportsBingoOdds.mlb-player-props.test.ts.
 */

type FixtureGame = (typeof fixtureGames)[number];

const DAY_MS = 24 * 60 * 60 * 1000;

/** The game under test is served as starting shortly from now, so the catalog accepts it. */
const startsAtFor = () => new Date(Date.now() + 3 * 60 * 60 * 1000).toISOString();

/**
 * One synthetic batter row per team carrying that team's whole box-score line.
 *
 * The candidate builder sums player rows into team totals, so a single row per team produces
 * exactly the same team aggregates a full roster would — and the per-player pool it also builds is
 * correctly too thin to emit named-player squares.
 *
 * `teams` is the matchup the rows are *labelled* for, which is not always the fixture game the
 * totals came from — see the history branch of the `/mlb/v1/games` mock below for why.
 */
const statRowsForGame = (game: FixtureGame, gameId: string, teams: { homeTeam: string; awayTeam: string }) =>
  (["home", "away"] as const).map((side) => {
    const totals = game.teamEventTotals[side];
    const teamName = side === "home" ? teams.homeTeam : teams.awayTeam;
    return {
      player: { id: side === "home" ? 900001 : 900002, first_name: "Team", last_name: side === "home" ? "Home" : "Away" },
      game_id: gameId,
      team: { display_name: teamName },
      team_name: teamName,
      hits: totals.hit,
      bb: totals.walk,
      hit_by_pitch: totals.hit_by_pitch,
      k: totals.strikeout,
      ground_outs: totals.groundout,
      fly_outs: totals.flyout,
      plate_appearances: 38,
    };
  });

/** The fixture game currently being served as "upcoming"; the rest become its recent history. */
let activeIndex = 0;

vi.mock("@/lib/ballDontLieClient", () => ({
  isBallDontLieConfigured: () => true,
  fetchBallDontLieJson: async () => ({}),
  fetchBallDontLieList: async (path: string, query: URLSearchParams) => {
    const active = fixtureGames[activeIndex]!;

    if (path === "/mlb/v1/games") {
      const dates = query.getAll("dates[]");
      const startsAt = startsAtFor();
      const today = startsAt.slice(0, 10);
      // The catalog asks for the lookahead window; the candidate builder asks for the 21 days
      // before the game. Serving the upcoming game only to the former keeps the two apart.
      if (dates.includes(today)) {
        return [
          {
            id: active.id,
            date: startsAt,
            status: "STATUS_SCHEDULED",
            home_team: { display_name: active.homeTeam, full_name: active.homeTeam },
            away_team: { display_name: active.awayTeam, full_name: active.awayTeam },
          },
        ];
      }
      // History: every other fixture game's box-score line, dated inside the lookback window and
      // **labelled with the active matchup's own two clubs**, so both teams accumulate the trailing
      // rates-allowed that Phase 7 prices against.
      //
      // The relabelling is the point, and it was the bug. `relatedGameIds` in
      // `buildMLBPlayerPropCandidatesFromRecentStats` keeps only history games involving one of the
      // two teams in the matchup; with the history carrying each fixture game's *own* teams, a
      // matchup whose clubs appear nowhere else in the frozen thirteen-game fixture got an empty
      // history, no team-event block, and therefore no board at all. Fixture game 0 is
      // Dodgers @ Diamondbacks and no other fixture game involves either club, so this file failed
      // deterministically on its very first game. The totals are still thirteen different real
      // box-score lines; only the nameplate on them changes.
      return fixtureGames
        .filter((_, index) => index !== activeIndex)
        .map((_, index) => ({
          id: `hist-${index}`,
          date: new Date(Date.now() - (index + 2) * DAY_MS).toISOString(),
          status: "STATUS_FINAL",
          home_team: { display_name: active.homeTeam, full_name: active.homeTeam },
          away_team: { display_name: active.awayTeam, full_name: active.awayTeam },
        }));
    }

    if (path === "/mlb/v1/stats") {
      const ids = query.getAll("game_ids[]");
      const rows: Array<Record<string, unknown>> = [];
      for (const id of ids) {
        const historyIndex = Number.parseInt(id.replace("hist-", ""), 10);
        if (!Number.isFinite(historyIndex)) continue;
        const source = fixtureGames.filter((_, index) => index !== activeIndex)[historyIndex];
        if (!source) continue;
        rows.push(...statRowsForGame(source, id, { homeTeam: active.homeTeam, awayTeam: active.awayTeam }));
      }
      return rows;
    }

    return [];
  },
}));

/**
 * 12 boards per game across 13 games = 156 boards. The generator samples many candidate sets per
 * board, so this is enough to make a systematic miss obvious without making the suite slow.
 */
const TRIALS_PER_GAME = 12;

type SlateResult = {
  boards: number;
  predicted: number[];
  wins: number;
  teamEventSquares: number;
  playableSquares: number;
  teamEventProbabilities: number[];
  thresholdsByEvent: Map<string, Set<number>>;
};

const runSlate = async (): Promise<SlateResult> => {
  const predicted: number[] = [];
  const teamEventProbabilities: number[] = [];
  const thresholdsByEvent = new Map<string, Set<number>>();
  let wins = 0;
  let teamEventSquares = 0;
  let playableSquares = 0;

  for (let index = 0; index < fixtureGames.length; index += 1) {
    activeIndex = index;
    const game = fixtureGames[index]!;
    // The catalog and candidate caches are keyed by sport/game and would otherwise serve the first
    // fixture game's board for all thirteen.
    vi.resetModules();
    const sportsBingo = await import("@/lib/sportsBingo");

    for (let trial = 0; trial < TRIALS_PER_GAME; trial += 1) {
      const built = await sportsBingo.buildSportsBingoBoardWithResolvers({
        gameId: game.id,
        sportKey: "baseball_mlb",
      });
      if (!built) continue;

      const playable = built.squares.filter((square) => !square.isFree);
      playableSquares += playable.length;
      for (const square of playable) {
        if (square.resolver.kind !== "mlb_webhook_team_event_at_least") continue;
        teamEventSquares += 1;
        teamEventProbabilities.push(square.probability);
        const seen = thresholdsByEvent.get(square.resolver.event) ?? new Set<number>();
        seen.add(square.resolver.threshold);
        thresholdsByEvent.set(square.resolver.event, seen);
      }

      const outcomes = sportsBingo.gradeResolversAgainstCompletedMLBGame({
        gameId: game.id,
        homeTeam: game.homeTeam,
        awayTeam: game.awayTeam,
        homeScore: game.homeScore,
        awayScore: game.awayScore,
        teamEventTotals: game.teamEventTotals,
        resolvers: playable.map((square) => square.resolver),
      });

      const marks = playable.map((square, position) => ({
        index: square.index,
        hit: outcomes[position]!.status === "hit",
      }));

      predicted.push(built.boardProbability);
      if (sportsBingo.boardStatusesMakeALine(marks)) wins += 1;
    }
  }

  return {
    boards: predicted.length,
    predicted,
    wins,
    teamEventSquares,
    playableSquares,
    teamEventProbabilities,
    thresholdsByEvent,
  };
};

describe("MLB win-rate calibration (Phase 7)", () => {
  let slate: SlateResult;

  beforeAll(async () => {
    slate = await runSlate();
  }, 120_000);

  it("builds a full board for every game on the slate", () => {
    expect(slate.boards).toBe(fixtureGames.length * TRIALS_PER_GAME);
    expect(slate.playableSquares / slate.boards).toBe(24);
  });

  it("predicts every board inside the 20-30% target band", () => {
    const outOfBand = slate.predicted.filter((probability) => probability < 0.2 || probability > 0.3);
    expect(outOfBand.length / slate.boards).toBeLessThan(0.05);

    const mean = slate.predicted.reduce((a, b) => a + b, 0) / slate.boards;
    expect(mean).toBeGreaterThan(0.2);
    expect(mean).toBeLessThan(0.3);
  });

  it("realizes a win rate near the predicted rate against real settled outcomes", () => {
    const realized = slate.wins / slate.boards;
    const meanPredicted = slate.predicted.reduce((a, b) => a + b, 0) / slate.boards;

    // Thirteen fixed games is a small slate and the band is correspondingly wide — the assertion
    // that matters is the second one. A generator predicting 25% while boards realize 45% has
    // failed even if each number looks defensible alone; that was precisely the pre-Phase-7 state.
    expect(realized).toBeGreaterThan(0.1);
    expect(realized).toBeLessThan(0.45);
    expect(Math.abs(realized - meanPredicted)).toBeLessThan(0.15);
  });

  it("still puts the team-event block on the board", () => {
    // Phase 7 re-priced this block; it must not have priced it off the board entirely. Production
    // boards on 2026-08-17 carried 7-10 of these out of 24.
    const perBoard = slate.teamEventSquares / slate.boards;
    expect(perBoard).toBeGreaterThan(3);
    expect(perBoard).toBeLessThan(14);
  });

  it("keeps the block's realized prices below the core markets", () => {
    // The block averaged 0.613 before Phase 7 — above the ~0.50 core markets, which is what made a
    // 25% board unbuildable. It now has to sit below them.
    const mean =
      slate.teamEventProbabilities.reduce((a, b) => a + b, 0) / slate.teamEventProbabilities.length;
    expect(mean).toBeLessThan(0.52);
    expect(mean).toBeGreaterThan(0.3);
  });

  it("varies each event's threshold across the slate rather than shipping a league constant", () => {
    // The regression this guards is silent: if the opponent lookup ever returns nothing, every
    // threshold collapses back to the league default and the squares still look perfectly fine.
    // On this thirteen-game slate that comes out as hits 8/9/10, strikeouts 8/9/10, groundouts
    // 8/9/10 and flyouts 5/6 — so the bar is ">1 distinct threshold", which is the literal
    // statement of "not a constant" and does not encode this fixture's exact spread.
    for (const event of ["hit", "strikeout", "groundout", "flyout"]) {
      const thresholds = slate.thresholdsByEvent.get(event);
      expect(thresholds, `no ${event} squares were generated`).toBeDefined();
      expect(thresholds!.size).toBeGreaterThan(1);
    }
  });

  it("never re-emits the near-automatic thresholds Phase 7 deleted", () => {
    const shipped: Record<string, number> = { hit: 5, walk: 2, strikeout: 5, groundout: 4, flyout: 4 };
    for (const [event, oldThreshold] of Object.entries(shipped)) {
      expect([...(slate.thresholdsByEvent.get(event) ?? [])]).not.toContain(oldThreshold);
    }
  });
});
